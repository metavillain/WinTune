<#
.SYNOPSIS
  Builds a portable, self-elevating WinTune.exe (single file, no install).

  The exe embeds the tweak catalog and the built-in templates, so it runs with no loose
  files. User-made templates and the restore state still live in %ProgramData%\WinTune.

  Backend: PS2EXE if available/installable (nicest - the exe elevates itself via its manifest).
  If PS2EXE can't be fetched (e.g. no internet), falls back to Windows' built-in IExpress.

.EXAMPLE
  .\Build-Exe.ps1
  .\Build-Exe.ps1 -Backend IExpress   # force the offline backend
#>
[CmdletBinding()]
param([ValidateSet('Auto', 'PS2EXE', 'IExpress')][string]$Backend = 'Auto')

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$dist = Join-Path $root 'dist'
$build = Join-Path $root 'build'
New-Item -ItemType Directory $dist, $build -Force | Out-Null
$combined = Join-Path $build 'WinTune.combined.ps1'
$exe = Join-Path $dist 'WinTune.exe'

function B64([string]$Path) { [Convert]::ToBase64String([IO.File]::ReadAllBytes($Path)) }

Write-Host 'Assembling single-file script...'
$catalogB64   = B64 (Join-Path $root 'data\tweaks.psd1')
$baseB64      = B64 (Join-Path $root 'templates\base.json')
$aggressiveB64 = B64 (Join-Path $root 'templates\aggressive.json')
$noSecB64     = B64 (Join-Path $root 'templates\no-security.json')
$vmB64        = B64 (Join-Path $root 'templates\vm.json')
$iconPath     = Join-Path $root 'assets\wintune.ico'
$iconB64      = if (Test-Path $iconPath) { B64 $iconPath } else { '' }
$engine = Get-Content -Raw (Join-Path $root 'lib\Engine.ps1')
$gui    = Get-Content -Raw (Join-Path $root 'lib\Gui.ps1')
$engineB64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($engine))   # for the deployment-script exporter

$header = @"
# ================= WinTune single-file build (generated by Build-Exe.ps1) =================
`$script:EmbeddedCatalog = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$catalogB64'))
`$script:EmbeddedTemplates = [ordered]@{
  'base'        = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$baseB64'))
  'aggressive'  = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$aggressiveB64'))
  'no-security' = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$noSecB64'))
  'vm'          = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$vmB64'))
}
`$script:EmbeddedIcon = '$iconB64'
`$script:EmbeddedEngine = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$engineB64'))
"@

$entry = @'
# ---------------------------- entry ----------------------------
function Show-FatalError { param($m) try { Add-Type -AssemblyName PresentationFramework; [System.Windows.MessageBox]::Show("$m", 'WinTune error') | Out-Null } catch { } }

$admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $admin) {
    # Not elevated (IExpress backend path). Copy to a stable location and relaunch elevated,
    # so cleanup of any temp extraction folder cannot pull the script out from under us.
    $self = if ($PSCommandPath) { $PSCommandPath } else { $MyInvocation.MyCommand.Path }
    $stable = Join-Path $env:ProgramData 'WinTune\WinTune.run.ps1'
    New-Item -ItemType Directory (Split-Path $stable) -Force -ErrorAction SilentlyContinue | Out-Null
    try { Copy-Item $self $stable -Force } catch { }
    Start-Process powershell.exe -Verb RunAs -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-STA','-WindowStyle','Hidden','-File',"`"$stable`""
    return
}
if ([Threading.Thread]::CurrentThread.ApartmentState -ne 'STA') {
    $self = if ($PSCommandPath) { $PSCommandPath } else { $MyInvocation.MyCommand.Path }
    Start-Process powershell.exe -Verb RunAs -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-STA','-WindowStyle','Hidden','-File',"`"$self`""
    return
}
try { Show-WinTuneGui } catch { Show-FatalError $_ }
'@

Set-Content -Path $combined -Encoding UTF8 -Value ($header + "`r`n" + $engine + "`r`n" + $gui + "`r`n" + $entry)
Write-Host "  wrote $combined ($([math]::Round((Get-Item $combined).Length/1kb)) KB)"

# sanity: the generated script must parse
$pe = $null
[System.Management.Automation.Language.Parser]::ParseFile($combined, [ref]$null, [ref]$pe) | Out-Null
if ($pe) { throw "Generated script has parse errors:`n$($pe | Out-String)" }

function Build-WithPS2EXE {
    if (-not (Get-Module -ListAvailable -Name ps2exe)) {
        Write-Host 'Installing PS2EXE from PSGallery (one-time)...'
        try { Install-PackageProvider -Name NuGet -MinimumVersion 2.8.5.201 -Force -Scope CurrentUser -ErrorAction Stop | Out-Null } catch { }
        Install-Module ps2exe -Scope CurrentUser -Force -AllowClobber -ErrorAction Stop
    }
    Import-Module ps2exe -ErrorAction Stop
    Write-Host 'Compiling with PS2EXE...'
    $icon = Join-Path $root 'assets\wintune.ico'
    $p = @{ InputFile = $combined; OutputFile = $exe; requireAdmin = $true; STA = $true; NoConsole = $true
            title = 'WinTune'; product = 'WinTune'; description = 'Windows 11 debloat and tune'; company = 'WinTune' }
    if (Test-Path $icon) { $p.IconFile = $icon }
    Invoke-ps2exe @p
    Test-Path $exe
}

function Build-WithIExpress {
    Write-Host 'Building with IExpress (offline fallback)...'
    $sed = Join-Path $build 'WinTune.sed'
    $run = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -STA -WindowStyle Hidden -File WinTune.combined.ps1'
    $lines = @(
        '[Version]', 'Class=IEXPRESS', 'SEDVersion=3',
        '[Options]', 'PackagePurpose=InstallApp', 'ShowInstallProgramWindow=0', 'HideExtractAnimation=1',
        'UseLongFileName=1', 'InsideCompressed=0', 'CAB_FixedSize=0', 'CAB_ResvCodeSigning=0',
        'RebootMode=N', 'InstallPrompt=%InstallPrompt%', 'DisplayLicense=%DisplayLicense%',
        'FinishMessage=%FinishMessage%', "TargetName=%TargetName%", 'FriendlyName=%FriendlyName%',
        'AppLaunched=%AppLaunched%', 'PostInstallCmd=%PostInstallCmd%', 'AdminQuietInstCmd=%AdminQuietInstCmd%',
        'UserQuietInstCmd=%UserQuietInstCmd%', 'SourceFiles=SourceFiles',
        '[Strings]', 'InstallPrompt=', 'DisplayLicense=', 'FinishMessage=',
        "TargetName=$exe", 'FriendlyName=WinTune', 'AppLaunched=' + $run,
        'PostInstallCmd=<None>', 'AdminQuietInstCmd=', 'UserQuietInstCmd=',
        'FILE0="WinTune.combined.ps1"',
        '[SourceFiles]', 'SourceFiles0=' + $build + '\',
        '[SourceFiles0]', '%FILE0%='
    )
    Set-Content -Path $sed -Value $lines -Encoding ASCII
    Start-Process -FilePath "$env:WINDIR\System32\iexpress.exe" -ArgumentList '/N', "`"$sed`"" -Wait
    Test-Path $exe
}

$ok = $false
if (Test-Path $exe) { Remove-Item $exe -Force }
switch ($Backend) {
    'PS2EXE'   { $ok = Build-WithPS2EXE }
    'IExpress' { $ok = Build-WithIExpress }
    default {
        try { $ok = Build-WithPS2EXE }
        catch { Write-Warning "PS2EXE backend failed: $($_.Exception.Message)"; Write-Host 'Falling back to IExpress...'; $ok = Build-WithIExpress }
    }
}

if ($ok -and (Test-Path $exe)) {
    Write-Host ("`nBuilt: {0}  ({1:N0} KB)" -f $exe, ((Get-Item $exe).Length / 1kb)) -ForegroundColor Green
} else {
    throw 'Build failed - no exe produced.'
}
